export const fmt = (x: number | null | undefined, nd = 1) =>
  x === null || x === undefined || Number.isNaN(x) ? "—" : x.toFixed(nd).replace(".", ",");

export const signed = (x: number | null | undefined, nd = 1) =>
  x === null || x === undefined ? "—" : (x > 0 ? "+" : x < 0 ? "−" : "") + fmt(Math.abs(x), nd);
